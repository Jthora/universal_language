#!/usr/bin/env ruby
# frozen_string_literal: true
#
# check-chirality.rb — is the imported register's handedness column DERIVABLE?
#
# WHY THIS EXISTS (notes 071, 076)
#   071 ran the derivation loop against the four named orbits with named neighbours and found
#   three of four blocked. Two of the three were blocked on the same thing — chirality — and 071
#   concluded the missing instrument was the PLACEMENT PLANE, and put "build the placement plane"
#   first in its recommendations.
#
#   That diagnosis was wrong, and this checker is what shows it. The register already carries
#   handedness for 180 (operator, a, b) cells and a measured mirror-distance for each of the six
#   marks. Nothing had ever compared the two sheets, so nobody noticed that (a) the whole
#   `inherited` class follows from one bit of the mark table, and (b) the `arrangement` class is
#   generated by a rule with a FOUR-CELL HOLE, which a third sheet independently contradicts.
#
# WHAT IT DERIVES
#   A plane figure is achiral iff its symmetry group contains a reflection — iff the group is
#   dihedral or orthogonal (D_n, O(2)) rather than cyclic (C_n). The `enantiomorphs` sheet
#   publishes a group per mark:
#
#     Point O(2) · Circle O(2) · Line D2 · Angle D1 · Curve D1 · Wave C2
#
#   Exactly one is cyclic. WAVE IS THE UNIQUE CHIRAL LETTER OF THE ALPHABET, and it is the smooth
#   C2 one: the Line's half-turn is also realised by a reflection (D2 contains C2), while
#   reflecting a sine in any line returns a half-period shift, never the sine. The same sheet's
#   independently MEASURED mirror distances agree — 0.388 for Wave against <= 0.008 for the other
#   five, with the threshold at 0.11, so the classification does not sit near the cut.
#
#   From that one bit the `inherited` class follows with no free parameters:
#     INHERITED  <=>  Wave is an operand.                      (55 cells, exact, 0 exceptions)
#
#   The `arrangement` class needs a per-operator rule, and that rule IS FITTED to this column —
#   see SCOPE. Operators fall into three classes by what the placement leaves free:
#     concentric (nest, superpose_concentric)   arrangement NEVER
#     crossing   (cross)                        iff a != b and BOTH operands are modulating (C1)
#     displacing (concatenate, superpose_displaced)
#                                               iff a != b and AT LEAST ONE is modulating (C1)
#
#   The concentric exclusion is the one part with an argument rather than a fit: at separation
#   r = 0 the relative-rotation parameter is free and the shared centre lets each mark's mirror
#   axis be rotated onto the other's, so a common axis always exists when both marks have one.
#   That is the placement plane's own statement about its degenerate radius — which is why the
#   plane is not the missing instrument here. It was never needed for THESE orbits.
#
# THE HOLE, AND WHY IT IS THE RULE THAT IS RIGHT
#   The rule predicts 30 arrangement cells. The sheet attests 26. The four it adds are exactly
#
#     {concatenate, superpose_displaced} x {(Angle,Curve), (Curve,Angle)}
#
#   i.e. the both-modulating case under the displacing operators — consistent with a generator
#   that enumerated {C1 mark} x {Point, Circle, Line} and so silently dropped {C1} x {C1}.
#
#   Those four cells are two orbits, 40 and 53. A THIRD sheet — the per-orbit records under
#   find/ — independently publishes `mirror_axes: 0` for both, and no mirror axis means chiral.
#   So on precisely the cells where the rule contradicts the handedness sheet, a sheet the rule
#   never saw adjudicates in the rule's favour. This checker reports that adjudication rather
#   than asserting it, and FAILS if it ever stops holding.
#
# SCOPE — READ BEFORE QUOTING THIS
#   * The `inherited` half is NOT fitted. It is one bit read off a different sheet, and it is
#     exact in both directions.
#   * The `arrangement` half IS FITTED: the operator->class map and the C1 threshold per class
#     were chosen to reproduce this column. 99 of 180 cells are achiral, so a skewed column is
#     easy to fit, and agreement on the fitted part is worth much less than agreement on the
#     derived part. What makes it more than curve-fitting is the four-cell disagreement being
#     resolved by a third sheet — a prediction the fit could have failed.
#   * `mirror_axes: 0 => chiral` is the definition, not a model. But the orbit sheet's mirror
#     counts are the Codex's measurements, not this repo's, and are inherited at their tier.
#   * 7 of the 93 orbits are generated by unary operators (close, reflect_pair) and carry no
#     cell in the handedness sheet. They are out of this checker's reach and counted as such.
#
#   Usage:  ruby tools/check-chirality.rb [--json] [--verbose] [--selftest]

require 'json'

REG      = 'uws/register/codex'
ENANT    = "#{REG}/charts/enantiomorphs.json"
HANDED   = "#{REG}/charts/chirality-source.cells.json"
FIND_DIR = "#{REG}/find"

json_out = ARGV.include?('--json')
verbose  = ARGV.include?('--verbose')
selftest = ARGV.include?('--selftest')

failures = []
notes    = []

def die(msg)
  warn "check-chirality.rb: #{msg}"
  exit 2
end

die "missing #{ENANT}"  unless File.exist?(ENANT)
die "missing #{HANDED}" unless File.exist?(HANDED)

# ---------------------------------------------------------------- the mark table
enant = JSON.parse(File.read(ENANT))
rows  = enant.fetch('rows')
thresh = enant.fetch('threshold')

# chiral <=> the symmetry group contains no reflection <=> the group is cyclic
CYCLIC = /\AC(\d+|inf)\z/
group_of  = {}
chiral_of = {}
rows.each do |r|
  m = r.fetch('mark')
  group_of[m]  = r.fetch('group')
  chiral_of[m] = CYCLIC.match?(r.fetch('group'))
end

# 1. the group-theoretic derivation must reproduce the sheet's own chiral flag
rows.each do |r|
  m = r.fetch('mark')
  if chiral_of[m] != r.fetch('chiral')
    failures << "mark #{m}: group #{group_of[m]} is #{chiral_of[m] ? 'cyclic' : 'reflective'} " \
                "but sheet says chiral=#{r.fetch('chiral')}"
  end
end

# 2. and must agree with the sheet's independent MEASUREMENT
rows.each do |r|
  m = r.fetch('mark')
  measured = r.fetch('mirror_distance') > thresh
  if measured != chiral_of[m]
    failures << "mark #{m}: mirror_distance #{r.fetch('mirror_distance')} vs threshold #{thresh} " \
                "says chiral=#{measured}, group #{group_of[m]} says #{chiral_of[m]}"
  end
end

chiral_marks = chiral_of.select { |_, v| v }.keys.sort
notes << "chiral marks from group column: #{chiral_marks.join(', ')} " \
         "(of #{rows.size}; threshold #{thresh})"

# ---------------------------------------------------------------- the rule
MODULATING = %w[Angle Curve].freeze   # the C1 / D1 pair: exactly one mirror axis each
CONCENTRIC = %w[nest superpose_concentric].freeze
CROSSING   = %w[cross].freeze
DISPLACING = %w[concatenate superpose_displaced].freeze

def predict(op, a, b, chiral_of)
  return 'inherited' if chiral_of[a] || chiral_of[b]
  return 'achiral'   if a == b
  n = [a, b].count { |m| MODULATING.include?(m) }
  case op
  when *CONCENTRIC then 'achiral'
  when *CROSSING   then n == 2 ? 'arrangement' : 'achiral'
  when *DISPLACING then n >= 1 ? 'arrangement' : 'achiral'
  else                  nil        # operator this rule does not model
  end
end

# ---------------------------------------------------------------- compare
cells = JSON.parse(File.read(HANDED)).fetch('cells')
agree = 0
unmodelled = []
disputed = []
orbit_of = {}

cells.each do |c|
  op = c.fetch('operator'); a = c.fetch('a'); b = c.fetch('b')
  attested = c.fetch('source')
  orbit_of[[op, a, b]] = c.fetch('orbit')
  got = predict(op, a, b, chiral_of)
  if got.nil?
    unmodelled << [op, a, b]
  elsif got == attested
    agree += 1
  else
    disputed << { op: op, a: a, b: b, orbit: c.fetch('orbit'), attested: attested, predicted: got }
  end
  # the sheet's own two columns must not contradict each other
  if (c.fetch('chiral') == 'true') != (attested != 'achiral')
    failures << "#{op}(#{a},#{b}): chiral=#{c.fetch('chiral')} but source=#{attested}"
  end
end

notes << "handedness cells: #{cells.size}; rule agrees on #{agree}, " \
         "disputes #{disputed.size}, does not model #{unmodelled.size}"

# ---------------------------------------------------------------- adjudicate by a third sheet
# mirror_axes == 0 means no mirror axis means chiral. The orbit records never informed the rule.
mirror_axes = {}
members_of  = {}
rec_of      = {}
Dir.glob("#{FIND_DIR}/*.json").each do |f|
  d = JSON.parse(File.read(f))
  next unless d.is_a?(Hash) && d.key?('orbit')
  o = d['orbit'].to_s
  mirror_axes[o] = d['mirror_axes'].to_s
  members_of[o]  = Array(d['members'])
  rec_of[o]      = d
end
die "no orbit records under #{FIND_DIR}" if mirror_axes.empty?

adjudicated = []
disputed.each do |d|
  ma = mirror_axes[d[:orbit].to_s]
  if ma.nil?
    failures << "orbit #{d[:orbit]} disputed but has no record under find/ to adjudicate with"
    next
  end
  third_says_chiral = (ma == '0')
  rule_says_chiral  = (d[:predicted] != 'achiral')
  d[:mirror_axes] = ma
  d[:third_sheet] = third_says_chiral ? 'chiral' : 'achiral'
  d[:verdict]     = if third_says_chiral == rule_says_chiral
                      'rule upheld'
                    else
                      'rule refuted'
                    end
  adjudicated << d
end

refuted = adjudicated.count { |d| d[:verdict] == 'rule refuted' }
if refuted.positive?
  failures << "the third sheet refutes the rule on #{refuted} disputed orbit(s) — " \
              'the rule is wrong, not the handedness column'
end

# ------------------------------------------------- UNRESOLVED: what is `components`?
# Recorded as NEITHER passed nor failed, per 075's third channel. Two readings are natural and
# BOTH are contradicted by the register's own numbers, so the field cannot be used as a
# topological invariant by anything importing this data -- and the honest report is that its
# semantics are unknown to me, not that the Codex is wrong.
#
# Restricted to BINARY orbits for reading A: `close(Angle)` has strokes 2 and one operand, so
# counting it as a two-mark composition was my error, not the register's.
unresolved = []
binary_orbits = orbit_of.values.map(&:to_s).uniq

mark_count_reading = binary_orbits.reject { |o| rec_of[o].nil? }
                                  .select  { |o| rec_of[o]['components'].to_s != '2' }
                                  .map     { |o| [o, members_of[o].first, rec_of[o]['components']] }

topo_reading = rec_of.keys.select { |o| rec_of[o]['crossings'].to_s != '0' }
                     .select     { |o| rec_of[o]['components'].to_s != '1' }
                     .map        { |o| [o, members_of[o].first, rec_of[o]['components']] }

# an orbit is an equivalence class and may hold both unary and binary members; show a BINARY
# one, or the example reads as a unary figure and misrepresents the counterexample.
binary_member = ->(o) { (members_of[o] || []).find { |m| m.count(',') == 1 } || members_of[o]&.first }
fmt = ->(list) { list.first(2).map { |o, _m, c| "orbit #{o} #{binary_member.call(o)} => #{c}" }.join('; ') }
unless mark_count_reading.empty?
  unresolved << ['`components` is not a count of the composed marks',
                 "#{mark_count_reading.size} of #{binary_orbits.size} binary orbits publish " \
                 "components != 2, e.g. #{fmt.call(mark_count_reading)}"]
end
unless topo_reading.empty?
  unresolved << ['`components` is not a count of connected pieces',
                 "#{topo_reading.size} orbit(s) with a crossing -- hence joined into one piece -- " \
                 "publish components != 1, e.g. #{fmt.call(topo_reading)}"]
end

# ---------------------------------------------------------------- selftest
if selftest
  st = []
  st << ['Wave is the unique chiral mark', chiral_marks == ['Wave']]
  # NOT written as a chain of ||: that form is satisfied by any one disjunct and so cannot fail.
  # One biconditional per cell, every cell, both directions.
  st << ['inherited <=> Wave is an operand',
         cells.all? { |c| (c['source'] == 'inherited') == (c['a'] == 'Wave' || c['b'] == 'Wave') }]
  # negative control: the same test must FAIL for a mark that is not the chiral one
  st << ['...and that test is not vacuous (fails for Angle)',
         !cells.all? { |c| (c['source'] == 'inherited') == (c['a'] == 'Angle' || c['b'] == 'Angle') }]
  st << ['concentric operators never arrange handedness',
         cells.none? { |c| CONCENTRIC.include?(c['operator']) && c['source'] == 'arrangement' }]
  st << ['the hole is the both-modulating displaced case',
         disputed.map { |d| [d[:op], d[:a], d[:b]].join('-') }.sort ==
           ['concatenate-Angle-Curve', 'concatenate-Curve-Angle',
            'superpose_displaced-Angle-Curve', 'superpose_displaced-Curve-Angle']]
  st << ['every disputed orbit is adjudicated by find/',
         adjudicated.size == disputed.size]
  puts 'selftest:'
  st.each { |name, ok| puts format('  %-52s %s', name, ok ? 'ok' : 'FAILED') }
  exit(st.all? { |_, ok| ok } ? 0 : 1)
end

# ---------------------------------------------------------------- report
if json_out
  puts JSON.pretty_generate(
    chiral_marks: chiral_marks,
    cells: cells.size,
    agree: agree,
    disputed: disputed,
    unmodelled: unmodelled.size,
    failures: failures
  )
else
  puts 'chirality — is the handedness column derivable?'
  puts
  puts '  mark table (group => chiral iff cyclic):'
  rows.each do |r|
    puts format('    %-7s %-5s mirror_distance %-8s  %s', r['mark'], r['group'],
                r['mirror_distance'], chiral_of[r['mark']] ? 'CHIRAL' : 'achiral')
  end
  puts
  notes.each { |n| puts "  #{n}" }
  puts
  unless disputed.empty?
    puts "  DISPUTED — rule contradicts the handedness sheet on #{disputed.size} cell(s):"
    adjudicated.each do |d|
      puts format('    %-22s %-7s %-7s orbit %-3s sheet=%-11s rule=%-11s mirror_axes=%-3s third sheet=%-8s %s',
                  d[:op], d[:a], d[:b], d[:orbit], d[:attested], d[:predicted],
                  d[:mirror_axes], d[:third_sheet], d[:verdict])
    end
    puts
    puts "  #{adjudicated.count { |d| d[:verdict] == 'rule upheld' }} upheld by a sheet the rule never saw, #{refuted} refuted."
    puts '  A disputed cell is not a defect in this repo: it is a hole in the imported column.'
    puts
  end
  unless unresolved.empty?
    puts '  UNRESOLVED — neither passed nor failed (075 REQ-3). Semantics I could not establish:'
    unresolved.each { |name, detail| puts "    ? #{name}: #{detail}" }
    puts '    Consequence: `components` must not be imported as a topological invariant.'
    puts
  end
  if verbose
    puts '  cells this rule does not model (unary operators):'
    puts "    #{unmodelled.empty? ? '(none)' : unmodelled.map { |o, a, b| "#{o}(#{a},#{b})" }.join(', ')}"
    reach = mirror_axes.keys.size - cells.map { |c| c['orbit'].to_s }.uniq.size
    puts "  orbits with no handedness cell at all: #{reach}"
    puts
  end
end

if failures.empty?
  puts '  OK — derivation holds; disputes adjudicated.' unless json_out
  exit 0
else
  puts '  FAILURES:' unless json_out
  failures.each { |f| puts "    - #{f}" } unless json_out
  exit 1
end
